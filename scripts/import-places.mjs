// Pulls towns, suburbs and neighbourhoods for Greater Accra, Ashanti and Central
// from OpenStreetMap (Overpass API) and writes a SQL file to load into Supabase.
//
//   node scripts/import-places.mjs
//   node scripts/import-places.mjs --from saved.json    (test with a saved Overpass response)
//
// Needs Node 18+ and internet access. Data (c) OpenStreetMap contributors, ODbL.
import { readFileSync, writeFileSync } from "node:fs";

const REGIONS = [
  { name: "Greater Accra", match: "^Greater Accra" },
  { name: "Ashanti", match: "^Ashanti" },
  { name: "Central", match: "^Central" },
];
const KINDS = "city|town|suburb|neighbourhood|quarter";
const OUT = "supabase/migrations/20261122000012_ghana_places.sql";
const ENDPOINTS = ["https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter"];

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;

function query(region) {
  return `[out:json][timeout:240];
area["ISO3166-1"="GH"][admin_level=2]->.gh;
rel(area.gh)["boundary"="administrative"]["admin_level"="4"]["name"~"${region.match}"];
map_to_area->.r;
node["place"~"^(${KINDS})$"]["name"](area.r);
out tags center;`;
}

async function fetchRegion(region) {
  let lastError;
  for (const url of ENDPOINTS) {
    try {
      const res = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/x-www-form-urlencoded", "User-Agent": "HandyCorp-import/1.0" },
        body: "data=" + encodeURIComponent(query(region)),
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return (await res.json()).elements ?? [];
    } catch (e) {
      lastError = e;
      console.error(`  ${url} failed: ${e.message}`);
    }
  }
  throw lastError;
}

const fromIdx = process.argv.indexOf("--from");
const saved = fromIdx > -1 ? JSON.parse(readFileSync(process.argv[fromIdx + 1], "utf8")) : null;

const rows = new Map(); // key: region|name lowercased
for (const region of REGIONS) {
  console.log(`Fetching ${region.name}…`);
  const els = saved ? (saved[region.name] ?? []) : await fetchRegion(region);
  let n = 0;
  for (const el of els) {
    const name = (el.tags?.name ?? "").trim();
    const lat = el.lat ?? el.center?.lat;
    const lon = el.lon ?? el.center?.lon;
    if (name.length < 2 || name.length > 60 || lat == null || lon == null) continue;
    const key = `${region.name}|${name.toLowerCase()}`;
    if (rows.has(key)) continue;
    rows.set(key, { region: region.name, name, kind: el.tags.place, lat, lon });
    n++;
  }
  console.log(`  ${n} places`);
  if (!saved) await new Promise((r) => setTimeout(r, 3000));
}

const list = [...rows.values()].sort((a, b) => a.region.localeCompare(b.region) || a.name.localeCompare(b.name));
if (list.length === 0) {
  console.error("No places found, so nothing was written.");
  process.exit(1);
}

const values = list.map((r) => {
  const slug = r.region === "Ashanti" ? slugify(r.name) : `${slugify(r.name)}-${slugify(r.region)}`;
  return `  (${sql(slug)}, ${sql(r.name)}, ${sql(r.region)}, ${sql(r.kind)}, ${r.lat.toFixed(6)}, ${r.lon.toFixed(6)})`;
});

writeFileSync(
  OUT,
  `-- Places in Greater Accra, Ashanti and Central from OpenStreetMap (c) OpenStreetMap contributors, ODbL.
-- Generated by scripts/import-places.mjs on ${new Date().toISOString().slice(0, 10)}. ${list.length} places.
-- Existing areas keep their names and only gain coordinates; nothing is deleted.

insert into public.areas (slug, name, region, kind, latitude, longitude, sort_order)
select v.slug, v.name, v.region, v.kind, v.lat, v.lon, 0
from (values
${values.join(",\n")}
) as v(slug, name, region, kind, lat, lon)
on conflict (slug) do update
  set latitude = coalesce(public.areas.latitude, excluded.latitude),
      longitude = coalesce(public.areas.longitude, excluded.longitude),
      kind = coalesce(public.areas.kind, excluded.kind);
`,
);
console.log(`\nWrote ${list.length} places to ${OUT}`);
